import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const webDir = path.join(root, "web");
const distDir = path.join(webDir, "dist");
const outFile = path.join(root, "src", "web-static.js");

const MIME = {
  ".js": "text/javascript",
  ".css": "text/css",
  ".html": "text/html",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".json": "application/json",
  ".txt": "text/plain",
  ".wasm": "application/wasm",
};

function walk(dir, base, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    const rel = path.posix.join(base, entry.name);
    if (entry.isDirectory()) {
      walk(abs, rel, out);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      out[`/${rel}`] = {
        type: MIME[ext] || "application/octet-stream",
        data: fs.readFileSync(abs).toString("base64"),
      };
    }
  }
}

console.log("🏗️  Building web app (vite build in web/ dir)…");
execSync("npm run build", { cwd: webDir, stdio: "inherit" });

const assets = {};
walk(distDir, "", assets);
if (!assets["/index.html"]) {
  console.error("✖ web/dist/index.html not found after build. Aborting.");
  process.exit(1);
}

const output = `// AUTO-GENERATED by scripts/build-web.js — do not edit.
// Embeds the built web app so the CLI is fully self-contained.
export const webAssets = ${JSON.stringify(assets)};
`;
fs.writeFileSync(outFile, output);
const kb = (Buffer.byteLength(output) / 1024).toFixed(0);
console.log(`✅ Embedded ${Object.keys(assets).length} asset(s) (${kb} KB) → src/web-static.js`);